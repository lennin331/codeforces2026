#include <iostream>
#include <vector>
#include <algorithm>
#include <map>

using namespace std;

// Memoization map to store the max value achievable from index i with a given prefix sum s
map<pair<int, long long>, long long> memo;

long long dfs(int i, long long s, const vector<long long>& a, long long current_max) {
    if (i == a.size()) {
        return current_max;
    }

    // Check memoization
    pair<int, long long> state = {i, s};
    if (memo.count(state)) {
        return memo[state];
    }

    long long best = current_max;

    // Option 1: a[i] - s
    long long val1 = a[i] - s;
    best = max(best, dfs(i + 1, s + val1, a, max(current_max, val1)));

    // Option 2: a[i]
    long long val2 = a[i];
    best = max(best, dfs(i + 1, s + val2, a, max(current_max, val2)));

    // Option 3: a[i] + s
    long long val3 = a[i] + s;
    best = max(best, dfs(i + 1, s + val3, a, max(current_max, val3)));

    return memo[state] = best;
}

void solve() {
    int n;
    cin >> n;
    
    vector<long long> a(n);
    for (int i = 0; i < n; ++i) {
        cin >> a[i];
    }
    
    memo.clear();
    
    // Start from index 1, initial prefix sum is a[0], initial max is a[0]
    long long ans = dfs(1, a[0], a, a[0]);
    cout << ans << "\n";
}

int main() {
    // Optimize standard I/O operations for speed
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t;
    cin >> t;
    while (t--) {
        solve();
    }
    
    return 0;
}